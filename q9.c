#include <stdio.h>
/*biblioteca para entrada e saída de dados do programa*/
int main (){
/*função principal do programa*/
int vida = 10;
/*declaração da variável inteira "vida"*/
vida ++;
/*incremento*/
printf ("Valor após o incremento: %d\n", vida);
/*impressão da saída de dados do incremento*/
vida --;
/*decremento*/
printf ("Valor após o decremento: %d\n", vida);
    /*impressão da saída de dados do decremento*/
    return 0;
}